"""Provider-agnostic manifests, safety validation and deterministic SFZ export."""
from __future__ import annotations
from dataclasses import dataclass, asdict
from pathlib import Path
import hashlib
import json
import re
import shutil

ALLOWED = re.compile(r"^[A-Za-z0-9_.-]+$")

@dataclass(frozen=True)
class Note:
    midi: int
    velocity: int
    wav: str
    confidence: float | None = None

    def validate(self, root: Path) -> None:
        if not 0 <= self.midi <= 127:
            raise ValueError("MIDI pitch out of range")
        if not 1 <= self.velocity <= 127:
            raise ValueError("velocity out of range")
        if self.confidence is not None and not (0 <= self.confidence <= 1):
            raise ValueError("confidence out of range")
        if not ALLOWED.fullmatch(self.wav) or not self.wav.lower().endswith('.wav'):
            raise ValueError("sample filenames must be local simple .wav basenames")
        if not (root / self.wav).is_file():
            raise FileNotFoundError(root / self.wav)


def create_sfz(samples_dir: Path, out_dir: Path, notes: list[Note], *, name: str = 'instrument') -> dict:
    if not ALLOWED.fullmatch(name):
        raise ValueError("invalid instrument name")
    if not notes:
        raise ValueError("at least one sample required")
    if len({(n.midi, n.velocity) for n in notes}) != len(notes):
        raise ValueError("duplicate pitch+velocity zone")
    samples_dir = samples_dir.resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    for n in notes:
        n.validate(samples_dir)
    ordered = sorted(notes, key=lambda n: (n.midi, n.velocity))
    keys = sorted({n.midi for n in ordered})
    limits = {}
    for i, k in enumerate(keys):
        lo = 0 if i == 0 else (keys[i-1] + k) // 2 + 1
        hi = 127 if i == len(keys) - 1 else (k + keys[i+1]) // 2
        limits[k] = (lo, hi)
    lines = ["// Generated by mixture-instrument-factory", "<control> default_path=Samples/"]
    manifest = []
    copied = {}
    for n in ordered:
        if n.wav not in copied:
            dest = out_dir / 'Samples' / n.wav
            dest.parent.mkdir(exist_ok=True, parents=True)
            shutil.copyfile(samples_dir / n.wav, dest)
            copied[n.wav] = hashlib.sha256(dest.read_bytes()).hexdigest()
        peers = sorted(x.velocity for x in ordered if x.midi == n.midi)
        index = peers.index(n.velocity)
        lovel = 1 if index == 0 else (peers[index-1] + n.velocity) // 2 + 1
        hivel = 127 if index == len(peers)-1 else (n.velocity + peers[index+1]) // 2
        lo, hi = limits[n.midi]
        lines.append(f"<region> sample={n.wav} pitch_keycenter={n.midi} lokey={lo} hikey={hi} lovel={lovel} hivel={hivel} ampeg_release=0.25")
        manifest.append({**asdict(n), 'lokey': lo, 'hikey': hi, 'lovel': lovel, 'hivel': hivel, 'sha256': copied[n.wav]})
    (out_dir / (name + '.sfz')).write_text('\n'.join(lines)+'\n', encoding='utf-8')
    info = {'name': name, 'format': 'sfz', 'player_required': True, 'claims': 'sample-library-only; VST3 plugin not built', 'notes': manifest}
    (out_dir / 'manifest.json').write_text(json.dumps(info, indent=2, ensure_ascii=False)+'\n',encoding='utf-8')
    return info


def parse_notes(path: Path) -> list[Note]:
    obj = json.loads(path.read_text(encoding='utf-8'))
    if not isinstance(obj, list):
        raise ValueError('notes file must be a JSON array')
    return [Note(**n) for n in obj]
